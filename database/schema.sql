-- SIPINJAM OKI Polinema - skema PostgreSQL
-- Pakai:  createdb sipinjam_oki
--         psql -d sipinjam_oki -f database/schema.sql -f database/seed.sql

BEGIN;

DROP TABLE IF EXISTS notifikasi, riwayat_status, peminjaman_item, peminjaman,
                     barang, kategori, pengguna, organisasi CASCADE;

CREATE TABLE organisasi (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama              VARCHAR(150) NOT NULL,
    jenis             VARCHAR(20)  NOT NULL CHECK (jenis IN ('BEM', 'HMJ', 'UKM', 'Lainnya')),
    kontak            VARCHAR(20)  NOT NULL DEFAULT '',
    status_verifikasi VARCHAR(20)  NOT NULL DEFAULT 'menunggu'
                      CHECK (status_verifikasi IN ('menunggu', 'terverifikasi', 'ditolak')),
    dibuat_pada       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_organisasi_nama ON organisasi (lower(nama));

CREATE TABLE pengguna (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id        INTEGER REFERENCES organisasi (id) ON DELETE CASCADE,
    nama          VARCHAR(150) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(10)  NOT NULL CHECK (role IN ('admin', 'oki')),
    aktif         BOOLEAN      NOT NULL DEFAULT TRUE,
    dibuat_pada   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (role = 'admin' OR org_id IS NOT NULL)
);
CREATE UNIQUE INDEX uq_pengguna_email ON pengguna (lower(email));
CREATE INDEX idx_pengguna_org ON pengguna (org_id);

CREATE TABLE kategori (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(100) NOT NULL UNIQUE
);
