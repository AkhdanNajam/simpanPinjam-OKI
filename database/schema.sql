CREATE TABLE barang (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id       INTEGER      NOT NULL REFERENCES organisasi (id) ON DELETE CASCADE,
    kategori_id  INTEGER      NOT NULL REFERENCES kategori (id),
    nama         VARCHAR(150) NOT NULL,
    deskripsi    VARCHAR(500) NOT NULL DEFAULT '',
    jumlah_total INTEGER      NOT NULL CHECK (jumlah_total >= 1),
    kondisi      VARCHAR(20)  NOT NULL CHECK (kondisi IN ('baik', 'rusak ringan', 'rusak berat')),
    lokasi       VARCHAR(150) NOT NULL DEFAULT '',
    maks_hari    INTEGER      NOT NULL CHECK (maks_hari >= 1),
    status       VARCHAR(10)  NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'nonaktif')),
    dibuat_pada  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_barang_org ON barang (org_id);

CREATE TABLE peminjaman (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peminjam_org_id  INTEGER      NOT NULL REFERENCES organisasi (id),
    pemilik_org_id   INTEGER      NOT NULL REFERENCES organisasi (id),
    keperluan        VARCHAR(255) NOT NULL,
    catatan          VARCHAR(255) NOT NULL DEFAULT '',
    tgl_pinjam       DATE         NOT NULL,
    tgl_rencana      DATE         NOT NULL,   -- rencana tanggal kembali
    tgl_aktual       DATE,                    -- tanggal kembali sebenarnya
    status           VARCHAR(15)  NOT NULL DEFAULT 'menunggu'
                     CHECK (status IN ('menunggu', 'disetujui', 'ditolak', 'dipinjam', 'selesai', 'dibatalkan')),
    alasan           VARCHAR(255) NOT NULL DEFAULT '',   -- alasan penolakan
    dibuat_pada      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (tgl_rencana >= tgl_pinjam),
    CHECK (peminjam_org_id <> pemilik_org_id)
);
CREATE INDEX idx_pinjam_peminjam ON peminjaman (peminjam_org_id);
CREATE INDEX idx_pinjam_pemilik  ON peminjaman (pemilik_org_id);
CREATE INDEX idx_pinjam_status   ON peminjaman (status);

CREATE TABLE peminjaman_item (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peminjaman_id   INTEGER NOT NULL REFERENCES peminjaman (id) ON DELETE CASCADE,
    barang_id       INTEGER NOT NULL REFERENCES barang (id),   -- RESTRICT: barang berriwayat tidak bisa dihapus
    jumlah          INTEGER NOT NULL CHECK (jumlah >= 1),
    kondisi_keluar  VARCHAR(20) CHECK (kondisi_keluar IN ('baik', 'rusak ringan', 'rusak berat')),
    kondisi_kembali VARCHAR(20) CHECK (kondisi_kembali IN ('baik', 'rusak ringan', 'rusak berat')),
    catatan_kembali VARCHAR(255) NOT NULL DEFAULT ''
);
CREATE INDEX idx_item_peminjaman ON peminjaman_item (peminjaman_id);
CREATE INDEX idx_item_barang     ON peminjaman_item (barang_id);

CREATE TABLE riwayat_status (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peminjaman_id INTEGER      NOT NULL REFERENCES peminjaman (id) ON DELETE CASCADE,
    pengguna_id   INTEGER      NOT NULL REFERENCES pengguna (id),
    status_lama   VARCHAR(15)  NOT NULL DEFAULT '',
    status_baru   VARCHAR(15)  NOT NULL,
    keterangan    VARCHAR(255) NOT NULL DEFAULT '',
    waktu         TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_riwayat_peminjaman ON riwayat_status (peminjaman_id);

CREATE TABLE notifikasi (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengguna_id   INTEGER      NOT NULL REFERENCES pengguna (id) ON DELETE CASCADE,
    peminjaman_id INTEGER      NOT NULL REFERENCES peminjaman (id) ON DELETE CASCADE,
    judul         VARCHAR(100) NOT NULL,
    pesan         VARCHAR(500) NOT NULL,
    sudah_baca    BOOLEAN      NOT NULL DEFAULT FALSE,
    waktu         TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_notif_pengguna ON notifikasi (pengguna_id, sudah_baca);

COMMIT;
